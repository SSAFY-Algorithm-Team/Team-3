# 복기 2. 로봇청소기 커버리지
# 소요시간: __분 / 시도: __회

# n × n 크기의 사무실이 있습니다. 칸의 좌표는 (행, 열) 이고 각각 1 부터 n 까지입니다.
# robots 에는 로봇청소기가 놓인 칸들이 [행, 열] 형태로 주어집니다.
# walls 의 각 원소 [r1, c1, r2, c2] 는 인접한 두 칸 (r1, c1) 과 (r2, c2) 사이에 벽이 있다는 뜻입니다. 벽이 있으면 두 칸 사이를 오갈 수 없습니다.
# 로봇청소기는 상하좌우로만 이동하며, 거리 q 만큼 청소할 수 있습니다. 즉 어떤 로봇에서 벽을 통과하지 않고 q 칸 이내로 갈 수 있는 칸은 청소됩니다.
# 사무실의 모든 칸이 청소되려면 q 가 최소 얼마여야 하는지 구하세요.

# 제한
# 1 ≤ n ≤ 100
# 1 ≤ robots.length ≤ 30
# 대각선 이동은 불가능합니다.
# 모든 칸은 어떤 로봇에서든 도달 가능함이 보장됩니다.
# 반환값은 정수입니다.
# 예시
# n	robots	walls	result
# 3	[[1, 1]]	[]	4
# 5	[[1, 1], [5, 5]]	[]	4
# 8	[[1,1], [1,8], [8,1], [8,8]]	아래 참고	8
# walls = [[3,4,4,4], [3,5,4,5], [5,4,6,4], [5,5,6,5],
#          [4,3,4,4], [5,3,5,4], [4,5,4,6],
#          [2,2,2,3], [2,6,2,7], [7,2,7,3], [7,6,7,7],
#          [1,4,1,5], [8,4,8,5]]
# 첫 예제는 (1,1)에서 (3,3)까지 4칸이 가장 멉니다. 
# 세 번째 예제는 가운데 2×2 구역 (4,4)~(5,5)가 벽으로 둘러싸여 있고 (5,5) 오른쪽에만 틈이 있습니다. 
# 로봇이 네 귀퉁이에 다 있어도 그 틈으로 빙 돌아 들어가야 해서 (4,4)가 8칸으로 가장 멉니다.

from collections import deque

dr = [-1,1,0,0]
dc = [0,0,-1,1]

def bfs(n, robots, walls):
    blocked = set()

    for r1, c1, r2, c2 in walls: 
        r1 -= 1
        c1 -= 1
        r2 -= 1 
        c2 -= 1

        blocked.add((r1,c1,r2,c2))
        blocked.add((r2, c2, r1, c1))

    dist = [[-1] * n for _ in range(n)]
    q = deque()

    for r,c in robots:
        r -= 1
        c -= 1
        dist[r][c] = 0
        q.append((r,c))

    while q:
        r, c = q.popleft()

        for d in range(4):
            nr = r + dr[d]
            nc = c + dc[d]

            if 0 <= nr < n and 0<= nc < n: 
                if dist[nr][nc] == -1:
                    if (r,c,nr,nc) not in blocked:
                        dist[nr][nc] = dist[r][c] + 1
                        q.append((nr,nc))
    return dist


def sol(n, robots, walls):
    dist = bfs(n,robots,walls)
    answer = max(max(row) for row in dist)
    print(answer) 

sol(3, [[1, 1]], [])
sol(5, [[1, 1], [5, 5]], [])
