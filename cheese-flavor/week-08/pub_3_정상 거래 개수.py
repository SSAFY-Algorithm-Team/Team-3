# 정상처리 거래 개수 구하기(수량과 대금이 같아야함)
# 거래 정보: [약정 증권 수량, 전달된 증권 수량, 약정 대금, 지급된 대금]

transactions = [[100, 100, 5000, 5000], [200, 190, 8000, 8000], 
                [150, 150, 7000, 6900], [300, 300, 12000, 12000]
                ]

correct = 0 # 정상거래

# 비교
for t in transactions:
    if t[0] == t[1] and t[2] == t[3]:
        correct += 1

print(correct)

